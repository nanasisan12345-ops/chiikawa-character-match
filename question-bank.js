export const questionBank = scenes.map(([texts, options], slot) =>
  texts.map((text, variant) => ({
    slot,
    variant,
    text,
    options,
    story: variant === 2,
    weights: questions[slot].weights,
  })),
);
const randomFromSeed = (seed) => () => {
  seed = (Math.imul(1664525, seed) + 1013904223) >>> 0;
  return seed / 4294967296;
};
function shuffled(array, random) {
  const out = [...array];
  for (let i = out.length - 1; i > 0; i--) {
    const j = Math.floor(random() * (i + 1));
    [out[i], out[j]] = [out[j], out[i]];
  }
  return out;
}
export function legacyQuestionSet() {
  return questions.map((_, slot) => ({ slot, variant: -1 }));
}
export function validateQuestionSet(set) {
  return (
    Array.isArray(set) &&
    set.length === 28 &&
    new Set(set.map((x) => x?.slot)).size === 28 &&
    set.every(
      (x) =>
        Number.isInteger(x?.slot) &&
        x.slot >= 0 &&
        x.slot < 28 &&
        Number.isInteger(x.variant) &&
        x.variant >= -1 &&
        x.variant < 3,
    )
  );
}
export function createQuestionSet(seed, previous = []) {
  const random = randomFromSeed(seed),
    last = new Map(previous.map((x) => [x.slot, x.variant]));
  const storySlots = new Set(
    shuffled(
      questions.map((_, i) => i).filter((i) => last.get(i) !== 2),
      random,
    ).slice(0, 10),
  );
  return shuffled(
    questions.map((_, slot) => {
      const options = [0, 1].filter((v) => v !== last.get(slot));
      return {
        slot,
        variant: storySlots.has(slot)
          ? 2
          : options[Math.floor(random() * options.length)],
      };
    }),
    random,
  );
}
export function getQuestion(entry) {
  if (entry.variant === -1)
    return { ...questions[entry.slot], options: ANSWER_LABELS, story: false };
  return questionBank[entry.slot][entry.variant];
}
export function canonicalAnswers(answers, set = legacyQuestionSet()) {
  if (
    !validateQuestionSet(set) ||
    !Array.isArray(answers) ||
    answers.length !== 28
  )
    throw new TypeError("質問セットが不正です。");
  const canonical = Array(28);
  set.forEach((entry, i) => (canonical[entry.slot] = answers[i]));
  return canonical;
}
